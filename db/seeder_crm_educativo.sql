-- =============================================================================
-- 1. TABLAS CATÁLOGO Y LOOKUPS
-- =============================================================================

-- Tabla: roles
CREATE TABLE IF NOT EXISTS public.roles (
    id_rol bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(30) NOT NULL,
    descripcion character varying(150),
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP
);

-- Tabla: etapas_pipeline
CREATE TABLE IF NOT EXISTS public.etapas_pipeline (
    id_etapa bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(30) NOT NULL,
    orden integer NOT NULL
);

-- Tabla: origenes_lead
CREATE TABLE IF NOT EXISTS public.origenes_lead (
    id_origen bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(50) NOT NULL
);

-- Tabla: motivos_perdida
CREATE TABLE IF NOT EXISTS public.motivos_perdida (
    id_motivo bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(80) NOT NULL
);

-- Tabla: profesiones
CREATE TABLE IF NOT EXISTS public.profesiones (
    id_profesion bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(100) NOT NULL
);

-- Tabla: descuentos
CREATE TABLE IF NOT EXISTS public.descuentos (
    id_descuento bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(100) NOT NULL,
    porcentaje numeric(5,2) NOT NULL,
    descripcion character varying(255),
    activo boolean DEFAULT true NOT NULL
);

-- =============================================================================
-- 2. TABLAS DE USUARIOS Y ASIGNACIONES
-- =============================================================================

-- Tabla: usuarios
CREATE TABLE IF NOT EXISTS public.usuarios (
    id_usuario bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_rol bigint NOT NULL REFERENCES public.roles(id_rol) ON DELETE CASCADE,
    nombre_completo character varying(120) NOT NULL,
    correo character varying(120) NOT NULL UNIQUE,
    password_hash character varying(255) NOT NULL,
    activo boolean DEFAULT true NOT NULL,
    participa_round_robin boolean DEFAULT true NOT NULL,
    ultimo_acceso timestamp(0) without time zone,
    remember_token character varying(100),
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP
);

-- Tabla: coordinador_version (Web)
CREATE TABLE IF NOT EXISTS public.coordinador_version (
    id_usuario bigint NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
    id_version_externo bigint NOT NULL,
    PRIMARY KEY (id_usuario, id_version_externo)
);

-- Tabla: importaciones_csv (Web)
CREATE TABLE IF NOT EXISTS public.importaciones_csv (
    id_importacion bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
    nombre_archivo character varying(150) NOT NULL,
    total_filas integer,
    filas_exitosas integer,
    filas_fallidas integer,
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Tabla: importaciones_csv_errores (Web)
CREATE TABLE IF NOT EXISTS public.importaciones_csv_errores (
    id_error bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_importacion bigint NOT NULL REFERENCES public.importaciones_csv(id_importacion) ON DELETE CASCADE,
    numero_linea integer NOT NULL,
    motivo text NOT NULL
);

-- =============================================================================
-- 3. TABLA CENTRAL DE LEADS Y OFERTA ACADÉMICA
-- =============================================================================

-- Tabla: leads
CREATE TABLE IF NOT EXISTS public.leads (
    id_lead bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(120) NOT NULL,
    telefono character varying(20) NOT NULL,
    correo character varying(120),
    id_origen bigint NOT NULL REFERENCES public.origenes_lead(id_origen),
    id_etapa bigint DEFAULT 1 NOT NULL REFERENCES public.etapas_pipeline(id_etapa),
    id_vendedor bigint REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    id_motivo_perdida bigint REFERENCES public.motivos_perdida(id_motivo) ON DELETE SET NULL,
    comentario_perdida text,
    id_importacion bigint REFERENCES public.importaciones_csv(id_importacion) ON DELETE SET NULL,
    fecha_asignacion timestamp(0) without time zone,
    ci character varying(20),
    nombre_completo character varying(150),
    fecha_nacimiento date,
    ciudad character varying(60),
    created_by bigint NOT NULL REFERENCES public.usuarios(id_usuario),
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    id_profesion bigint REFERENCES public.profesiones(id_profesion) ON DELETE SET NULL,
    id_descuento bigint REFERENCES public.descuentos(id_descuento) ON DELETE SET NULL
);

-- Tabla: lead_interes
CREATE TABLE IF NOT EXISTS public.lead_interes (
    id_interes bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_lead bigint NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
    tipo character varying(10) NOT NULL,
    id_version_externo bigint,
    id_modulo_externo bigint,
    nombre_snapshot character varying(150) NOT NULL
);

-- Tabla: asignaciones_lead
CREATE TABLE IF NOT EXISTS public.asignaciones_lead (
    id_asignacion bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_lead bigint NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
    id_vendedor_anterior bigint REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    id_vendedor_nuevo bigint NOT NULL REFERENCES public.usuarios(id_usuario),
    asignado_por bigint NOT NULL REFERENCES public.usuarios(id_usuario),
    tipo character varying(20) NOT NULL,
    motivo character varying(200),
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- =============================================================================
-- 4. TABLAS DE PAGOS, MATRÍCULAS, BITÁCORA Y RECORDATORIOS
-- =============================================================================

-- Tabla: comprobantes_pago
CREATE TABLE IF NOT EXISTS public.comprobantes_pago (
    id_comprobante bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_lead bigint NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
    subido_por bigint NOT NULL REFERENCES public.usuarios(id_usuario),
    archivo_url character varying(255) NOT NULL,
    tipo_archivo character varying(10) DEFAULT 'TRANSF' NOT NULL,
    monto numeric(10,2),
    estado character varying(15) DEFAULT 'PENDIENTE' NOT NULL,
    revisado_por bigint REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    fecha_revision timestamp(0) without time zone,
    comentario_rechazo text,
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP
);

-- Tabla: envios_matricula
CREATE TABLE IF NOT EXISTS public.envios_matricula (
    id_envio bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_lead bigint NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
    id_comprobante bigint REFERENCES public.comprobantes_pago(id_comprobante) ON DELETE SET NULL,
    payload jsonb,
    estado character varying(15) DEFAULT 'PENDIENTE' NOT NULL,
    respuesta_api text,
    intentos integer DEFAULT 0 NOT NULL,
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP
);

-- Tabla: bitacora
CREATE TABLE IF NOT EXISTS public.bitacora (
    id_evento bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_lead bigint NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
    id_usuario bigint REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    tipo character varying(20) NOT NULL,
    descripcion text NOT NULL,
    id_etapa_anterior bigint REFERENCES public.etapas_pipeline(id_etapa) ON DELETE SET NULL,
    id_etapa_nueva bigint REFERENCES public.etapas_pipeline(id_etapa) ON DELETE SET NULL,
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Tabla: recordatorios
CREATE TABLE IF NOT EXISTS public.recordatorios (
    id_recordatorio bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_lead bigint NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
    id_usuario bigint NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
    fecha_hora timestamp(0) without time zone NOT NULL,
    descripcion character varying(255) NOT NULL,
    estado character varying(15) DEFAULT 'PENDIENTE' NOT NULL,
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP
);

